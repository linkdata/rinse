// Command precompile writes gVisor's systrap stubfilter_precompiled.go for the
// host architecture to stdout.
//
// The gVisor go branch ships that file generated on amd64 only, which makes
// the sentry panic on other architectures. build.sh writes this output over
// the file in a copy of the gVisor module.
package main

import (
	"fmt"
	"os"

	"gvisor.dev/gvisor/pkg/sentry/platform/systrap/stubfilter"
)

func main() {
	programs, err := stubfilter.PrecompiledPrograms()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// systrap only calls GetPrecompiled, so the rest of upstream's template is omitted.
	fmt.Print("// Code generated by rinse gvisor/precompile. DO NOT EDIT.\n\n")
	fmt.Print("package systrap\n\nimport \"gvisor.dev/gvisor/pkg/seccomp/precompiledseccomp\"\n\n")
	fmt.Print("func GetPrecompiled(programName string) (precompiledseccomp.Program, bool) {\n\tswitch programName {\n")
	for _, p := range programs {
		fmt.Print(p.SwitchCase("precompiledseccomp"))
	}
	fmt.Print("\t}\n\treturn precompiledseccomp.Program{}, false\n}\n")
}
